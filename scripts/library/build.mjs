// Builds src/data/library.json from the free-exercise-db snapshot plus
// routin.fit's own additions, aliases and overrides, and writes a review
// report to docs/library-report.md.
//
//   node scripts/library/build.mjs
//
// Source dataset: https://github.com/yuhonas/free-exercise-db (Unlicense).
// The snapshot is vendored so builds are reproducible; refresh it with
//   curl -L -o scripts/library/free-exercise-db.json \
//     https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  patternFor, jointsFor, equipmentFor, kindFor, deltoidHead, LENGTHENED_RE,
} from './rules.mjs';
import { normalizeName } from '../../src/lib/exerciseNames.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const read = (p) => JSON.parse(readFileSync(join(here, p), 'utf8'));

const KEEP_CATEGORIES = new Set(['strength', 'powerlifting', 'stretching']);
const IMAGE_BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/';

const rawText = readFileSync(join(here, 'free-exercise-db.json'), 'utf8');
const raw = JSON.parse(rawText);
const { exercises: additions } = read('additions.json');
const { aliases } = read('aliases.json');
const { overrides } = read('overrides.json');

function splitShoulders(muscles, pattern) {
  return muscles.map((m) => (m === 'shoulders' ? deltoidHead(pattern) : m));
}

function fromDataset(ex) {
  const pattern = ex.category === 'stretching' ? 'mobility' : patternFor(ex);
  const equipment = equipmentFor(ex);
  return {
    id: ex.id,
    name: ex.name,
    aliases: [],
    category: ex.category,
    mechanic: ex.mechanic ?? null,
    force: ex.force ?? null,
    level: ex.level,
    primaryMuscles: splitShoulders(ex.primaryMuscles, pattern),
    secondaryMuscles: splitShoulders(ex.secondaryMuscles, pattern),
    pattern,
    equipment,
    kind: kindFor(equipment),
    joints: pattern === 'mobility' ? [] : jointsFor(ex, pattern),
    lengthened: ex.category !== 'stretching' && LENGTHENED_RE.test(ex.name),
    instructions: ex.instructions,
    images: ex.images.map((p) => IMAGE_BASE + p),
    source: 'free-exercise-db',
  };
}

function fromAddition(ex) {
  return {
    aliases: [],
    images: [],
    ...ex,
    primaryMuscles: splitShoulders(ex.primaryMuscles, ex.pattern),
    secondaryMuscles: splitShoulders(ex.secondaryMuscles, ex.pattern),
    kind: kindFor(ex.equipment),
    source: 'routin.fit',
    aliases: ex.aliases ?? [],
  };
}

const excluded = raw.filter((ex) => !KEEP_CATEGORIES.has(ex.category));
const entries = [
  ...raw.filter((ex) => KEEP_CATEGORIES.has(ex.category)).map(fromDataset),
  ...additions.map(fromAddition),
];
const byId = new Map(entries.map((e) => [e.id, e]));

const errors = [];
for (const [id, patch] of Object.entries(overrides)) {
  const e = byId.get(id);
  if (!e) errors.push(`override for unknown id ${id}`);
  else Object.assign(e, patch, patch.equipment ? { kind: kindFor(patch.equipment) } : {});
}
for (const [alias, id] of Object.entries(aliases)) {
  const e = byId.get(id);
  if (!e) errors.push(`alias "${alias}" points to unknown id ${id}`);
  else e.aliases.push(alias);
}
for (const e of entries) e.aliases = [...new Set(e.aliases.map(normalizeName))].sort();

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

entries.sort((a, b) => a.name.localeCompare(b.name));
mkdirSync(join(root, 'src', 'data'), { recursive: true });
const sha = createHash('sha256').update(rawText).digest('hex').slice(0, 12);
const out = {
  source: 'free-exercise-db (Unlicense) + routin.fit additions',
  datasetSha256: sha,
  count: entries.length,
  exercises: entries,
};
writeFileSync(
  join(root, 'src', 'data', 'library.json'),
  `{\n"source":${JSON.stringify(out.source)},\n"datasetSha256":"${sha}",\n"count":${entries.length},\n"exercises":[\n${entries
    .map((e) => JSON.stringify(e))
    .join(',\n')}\n]}\n`,
);

// ---- review report ----
const count = (arr, key) =>
  Object.entries(arr.reduce((m, x) => ((m[key(x)] = (m[key(x)] ?? 0) + 1), m), {})).sort((a, b) => b[1] - a[1]);
const training = entries.filter((e) => e.category !== 'stretching');
const untagged = training.filter((e) => !e.pattern);
const lines = [
  '# Exercise library report',
  '',
  `Generated by \`scripts/library/build.mjs\`. Dataset snapshot sha256 \`${sha}…\`.`,
  '',
  `- **${entries.length}** exercises kept (${training.length} training, ${entries.length - training.length} stretching), ${additions.length} of them routin.fit additions.`,
  `- **${excluded.length}** left out by category: ${count(excluded, (e) => e.category).map(([k, v]) => `${k} ${v}`).join(', ')}.`,
  `- **${untagged.length}** training exercises have no movement pattern yet (listed below). They are kept but never suggested as swaps.`,
  '',
  'Tags are produced by name-based rules in `scripts/library/rules.mjs`; they are heuristics and need review. Fix individual entries in `overrides.json`.',
  '',
  '## Exercises per movement pattern',
  '',
  '| Pattern | Count | Examples |',
  '| --- | --- | --- |',
  ...count(training.filter((e) => e.pattern), (e) => e.pattern).map(
    ([p, n]) => `| ${p} | ${n} | ${training.filter((e) => e.pattern === p).slice(0, 4).map((e) => e.name).join(', ')} |`,
  ),
  '',
  '## Equipment',
  '',
  '| Equipment | Exercises |',
  '| --- | --- |',
  ...count(entries.flatMap((e) => (e.equipment.length ? e.equipment : ['none'])).map((x) => ({ x })), (o) => o.x).map(
    ([k, v]) => `| ${k} | ${v} |`,
  ),
  '',
  `## No movement pattern (${untagged.length})`,
  '',
  ...untagged.map((e) => `- ${e.name} (\`${e.id}\`)`),
  '',
];
mkdirSync(join(root, 'docs'), { recursive: true });
writeFileSync(join(root, 'docs', 'library-report.md'), lines.join('\n'));

console.log(`library: ${entries.length} exercises, ${untagged.length} without a pattern, sha ${sha}`);
